// psrAdvanceRef writes contents as a new commit on top of oldSHA and moves
// refs/heads/main to it entirely through plumbing against a scratch index, so
// the ref advances without the real index or the working tree ever being
// touched — the exact post-CAS precondition syncProtectedCheckout is designed
// for. Paths in oldSHA but absent from contents are carried forward unchanged.
func psrAdvanceRef(t *testing.T, dir, oldSHA string, contents map[string]string) string {
	t.Helper()
	idx := filepath.Join(t.TempDir(), "psr-index")
	env := append(os.Environ(), "GIT_INDEX_FILE="+idx)
	psrGitEnv(t, dir, env, "read-tree", oldSHA)
	for path, text := range contents {
		blob := psrHashObject(t, dir, env, text)
		psrGitEnv(t, dir, env, "update-index", "--add", "--cacheinfo", "100644,"+blob+","+path)
	}
	tree := psrGitEnv(t, dir, env, "write-tree")
	newSHA := git(t, dir, "commit-tree", tree, "-p", oldSHA, "-m", "landing")
	git(t, dir, "update-ref", "refs/heads/main", newSHA)
	return newSHA
}

func psrGitEnv(t *testing.T, dir string, env []string, args ...string) string {
	t.Helper()
	cmd := exec.Command("git", args...)
	cmd.Dir = dir
	cmd.Env = env
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("git %s: %v\n%s", strings.Join(args, " "), err, out)
	}
	return strings.TrimSpace(string(out))
}

func psrHashObject(t *testing.T, dir string, env []string, text string) string {
	t.Helper()
	cmd := exec.Command("git", "hash-object", "-w", "--stdin")
	cmd.Dir = dir
	cmd.Env = env
	cmd.Stdin = strings.NewReader(text)
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("git hash-object: %v\n%s", err, out)
	}
	return strings.TrimSpace(string(out))
}

func asProtectedSyncConflict(err error, target **ProtectedSyncConflictError) bool {
	return errors.As(err, target)
}
